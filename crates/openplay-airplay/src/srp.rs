//! SRP-6a client math for HAP pair-setup.
//!
//! HomeKit's `pair-setup` uses SRP-6a over the 3072-bit group with SHA-512 as
//! the hash. This module holds the pure computation so it can be tested against
//! an independent implementation of the server side; `hap_pairing` keeps the
//! I/O and TLV8 framing.
//!
//! Notation follows RFC 5054:
//!
//! ```text
//! x  = H(s | H(I | ":" | P))
//! A  = g^a mod N
//! u  = H(PAD(A) | PAD(B))
//! k  = H(N | PAD(g))
//! S  = (B - k * g^x) ^ (a + u * x) mod N
//! K  = H(S)
//! M1 = H(H(N) XOR H(g) | H(I) | s | A | B | K)
//! M2 = H(A | M1 | K)
//! ```

use num_bigint::BigUint;
use sha2::{Digest, Sha512};

/// SRP-6a group modulus `N` — the 3072-bit group, as adopted by RFC 5054
/// appendix A from RFC 3526 group 15.
