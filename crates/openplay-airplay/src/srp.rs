///
/// and `srp_group_matches_rfc3526_formula` in this module's tests re-derives it
/// from that formula at test time, so a corrupted digit cannot pass CI. The
/// other tests confirm the properties SRP depends on: 3072 bits, prime,
/// `(N-1)/2` prime, and `g = 5` a generator of the full group.
///
